// Regenerates src/lib/slug-redirects.ts from database/slug-name-fixes.csv.
// Usage: node scripts/generate-slug-redirects.mjs [inputCsv] [outputTs]
// Defaults are the repo paths, resolved from this file. Only rows with
// status "recovered" and a new slug different from the old slug produce a
// redirect. Not-truncated and unrecovered rows are left out on purpose:
// their URLs do not change.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const input = resolve(root, process.argv[2] || "database/slug-name-fixes.csv");
const output = resolve(root, process.argv[3] || "src/lib/slug-redirects.ts");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"') {
        if (text[i + 1] === '"') { field += '"'; i += 1; }
        else quoted = false;
      } else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") { row.push(field); field = ""; }
    else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i += 1;
      row.push(field); field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  const [header, ...body] = rows;
  return body.map((values) => Object.fromEntries(header.map((key, index) => [key, values[index] ?? ""])));
}

const rows = parseCsv(readFileSync(input, "utf8"));
const redirects = new Map();
let skippedNotTruncated = 0;
let skippedUnrecovered = 0;
for (const row of rows) {
  if (row.status !== "recovered") {
    if (row.status === "not-truncated") skippedNotTruncated += 1;
    else skippedUnrecovered += 1;
    continue;
  }
  if (!row.old_org_slug || !row.new_org_slug || row.old_org_slug === row.new_org_slug) continue;
  redirects.set(row.old_org_slug, row.new_org_slug);
}

const entries = [...redirects.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const lines = [
  "// Generated by scripts/generate-slug-redirects.mjs from database/slug-name-fixes.csv.",
  "// Do not edit by hand. Maps each truncated organization slug to the",
  "// recovered full organization slug. Old URLs 301 to the new slug once the",
  "// data migration has renamed the organization.",
  "export const slugRedirects: Record<string, string> = {",
  ...entries.map(([oldSlug, newSlug]) => `  ${JSON.stringify(oldSlug)}: ${JSON.stringify(newSlug)},`),
  "};",
  "",
  "export function resolveSlugRedirect(slug: string): string | null {",
  "  return slugRedirects[slug] ?? null;",
  "}",
  "",
];
writeFileSync(output, `${lines.join("\n")}`);
console.log(`Wrote ${entries.length} redirects to ${output} (${skippedNotTruncated} not-truncated and ${skippedUnrecovered} unrecovered rows skipped).`);
